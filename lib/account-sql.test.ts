import test from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { PGlite } from "@electric-sql/pglite";

const A = "10000000-0000-4000-8000-000000000001", B = "10000000-0000-4000-8000-000000000002";
const K = "20000000-0000-4000-8000-000000000001", K2 = "20000000-0000-4000-8000-000000000002";
const W = "30000000-0000-4000-8000-000000000001";
// Target is explicitly ephemeral PostgreSQL WASM memory. Never reads env, URLs, credential stores or disk databases.
// auth helpers below emulate verified PostgREST claims; they do not test Supabase signature verification.
test("isolated PostgreSQL executes account migration/RLS, ownership, atomic retries and tombstone denial", async () => {
  const db = await PGlite.create("memory://");
  try {
    await db.exec(`create role anon; create role authenticated; create role service_role bypassrls;
      create schema auth;
      grant usage on schema public,auth to anon,authenticated,service_role;
      create function auth.jwt() returns jsonb language sql stable as $$ select coalesce(nullif(current_setting('request.jwt.claims',true),''),'{}')::jsonb $$;
      create function auth.uid() returns uuid language sql stable as $$ select (auth.jwt()->>'sub')::uuid $$;
      create function auth.role() returns text language sql stable as $$ select auth.jwt()->>'role' $$;
      create table public.unrelated_sentinel(id integer primary key);
      insert into public.unrelated_sentinel values(7); grant select on public.unrelated_sentinel to authenticated;`);
    await db.exec(await readFile(new URL("../supabase/migrations/0006_wd_accounts.sql", import.meta.url), "utf8"));
    const login = async (role: "anon" | "authenticated" | "service_role", id?: string, age = 0) => {
      await db.exec("reset role");
      const claims = { role, sub: id, is_anonymous: false, amr: [{ method: "oauth", timestamp: Math.floor(Date.now() / 1000) - age }] };
      await db.query("select set_config('request.jwt.claims',$1,false)", [JSON.stringify(claims)]);
      await db.exec(`set role ${role}`);
    };
    const command = async (action: string, body = {}, key: string | null = K) => (await db.query<{ result: Record<string, unknown> }>("select public.wd_account_command($1,$2::jsonb,$3::uuid) as result", [action, JSON.stringify(body), key])).rows[0].result;
    await login("anon");
    await assert.rejects(db.query("select * from public.wd_accounts"), /permission denied/);
    await assert.rejects(command("initialize"), /permission denied/);
    await login("authenticated", A);
    assert.equal((await command("initialize", {}, null)).error, "invalid_command");
    assert.equal((await db.query("select * from public.wd_accounts")).rows.length, 0);
    const initialized = await command("initialize"); assert.equal(initialized.revision, 1);
    assert.deepEqual(await command("initialize"), initialized);
    assert.equal((await db.query("select * from public.unrelated_sentinel")).rows.length, 1);
    await assert.rejects(db.query("update public.wd_accounts set revision=99"), /permission denied/);
    await assert.rejects(db.query("insert into public.wd_saved_weeks(user_id,id,revision,week) values($1,$2,1,'{}')", [A, W]), /permission denied/);
    const prefs = { diet: "none", allergens: [], excludedSkuIds: [], household: 2, notifications: false };
    assert.equal((await command("update", { revision: 1, preferences: { ...prefs, tier: "protein" } }, K2)).error, "invalid_command");
    assert.equal((await command("update", { revision: 1, preferences: { ...prefs, household: null } }, K2)).error, "invalid_command");
    assert.equal((await command("update", { revision: 1, preferences: prefs }, K2)).revision, 2);
    assert.equal((await command("update", { revision: 1, preferences: prefs }, W)).error, "revision_conflict");
    assert.equal((await command("update", { revision: 2, preferences: prefs }, K2)).error, "idempotency_conflict");
    await login("authenticated", B); await command("initialize");
    assert.equal((await db.query<{ user_id: string }>("select user_id from public.wd_accounts")).rows[0].user_id, B);
    assert.equal((await db.query("select * from public.wd_accounts where user_id=$1", [A])).rows.length, 0);
    await assert.rejects(db.query("select * from public.wd_account_receipts"), /permission denied/);
    await login("service_role");
    await db.query("insert into public.wd_catalog_pins values($1,5,$2,'solver-test','[\"main\"]')", ["catalog-test", "a".repeat(64)]);
    await assert.rejects(db.query("update public.wd_catalog_pins set snapshot_version=6"), /permission denied/);
    await login("authenticated", A);
    const week = { snapshotVersion: 5, snapshotSha256: "a".repeat(64), solverRevision: "solver-test", catalogRevision: "catalog-test", recipeIds: Array(15).fill("main"), seed: 7 };
    assert.equal((await command("save_week", { id: W, revision: 0, week: { ...week, snapshotSha256: "b".repeat(64) } }, W)).error, "invalid_command");
    assert.equal((await command("save_week", { id: W, revision: 0, week }, W)).revision, 1);
    await login("authenticated", B);
    assert.equal((await command("list_weeks", { limit: 20, before: null }, null)).weeks instanceof Array, true);
    assert.deepEqual((await command("list_weeks", { limit: 20, before: null }, null)).weeks, []);
    assert.equal((await command("delete_week", { id: W, revision: 1 }, W)).error, "revision_conflict");
    await login("authenticated", A, 301);
    assert.equal((await command("begin_deletion", {}, A)).error, "invalid_command");
    await login("authenticated", A);
    assert.equal((await command("begin_deletion", {}, A)).error,"invalid_command","direct authenticated RPC must require intentional confirmation too");
    assert.equal((await command("begin_deletion", {confirmation:"yes"}, A)).error,"invalid_command");
    const deleted = await command("begin_deletion", {confirmation:"DELETE MY ACCOUNT"}, A); assert.equal(deleted.state, "deletion_pending");
    assert.deepEqual(await command("begin_deletion", {confirmation:"DELETE MY ACCOUNT"}, A), deleted);
    assert.equal((await command("initialize", {}, B)).error, "account_inactive");
    assert.equal((await command("read", {}, null)).error, "account_inactive");
    assert.equal((await db.query("select * from public.wd_saved_weeks")).rows.length, 0);
    assert.equal((await db.query("select * from public.wd_accounts")).rows.length, 0);
    assert.equal((await command("deletion_status", {}, null)).state, "deletion_pending");
  } finally { await db.close(); }
});
test("isolated PostgreSQL billing binds opaque identities, excludes clients, serializes events and preserves environment/ownership", async () => {
  const db = await PGlite.create("memory://");
  try {
    await db.exec(`create role anon; create role authenticated; create role service_role bypassrls;
      create schema auth; grant usage on schema public,auth to anon,authenticated,service_role;
      create function auth.jwt() returns jsonb language sql stable as $$ select coalesce(nullif(current_setting('request.jwt.claims',true),''),'{}')::jsonb $$;
      create function auth.uid() returns uuid language sql stable as $$ select (auth.jwt()->>'sub')::uuid $$;
      create function auth.role() returns text language sql stable as $$ select auth.jwt()->>'role' $$;`);
    for (const migration of ["0006_wd_accounts.sql", "0007_wd_billing.sql"]) await db.exec(await readFile(new URL(`../supabase/migrations/${migration}`, import.meta.url), "utf8"));
    const login = async (role: string, id?: string) => { await db.exec("reset role"); await db.query("select set_config('request.jwt.claims',$1,false)", [JSON.stringify({ role, sub: id })]); await db.exec(`set role ${role}`); };
    const bill = async (action: string, body: unknown) => (await db.query<{ result: Record<string, unknown> }>("select public.wd_billing_command($1,$2::jsonb) as result", [action, JSON.stringify(body)])).rows[0].result;
    await login("authenticated", A);
    await db.query("select public.wd_account_command('initialize','{}',$1)", [K]);
    for (const table of ["wd_billing_bindings", "wd_billing_states", "wd_billing_transactions", "wd_billing_events"]) await assert.rejects(db.query(`select * from public.${table}`), /permission denied/);
    await assert.rejects(bill("bind", { userId: A }), /permission denied/);
    await login("authenticated", B); await db.query("select public.wd_account_command('initialize','{}',$1)", [K]);
    await login("service_role");
    const a = await bill("bind", { userId: A }); const b = await bill("bind", { userId: B });
    assert.match(a.appUserId as string, /^wd_[0-9a-f-]{36}$/); assert.notEqual(a.appUserId, `wd_${A}`);
    assert.notEqual(a.appUserId,b.appUserId); assert.deepEqual(await bill("bind", { userId: A }),a);
    const begin = () => bill("begin", { userId: A, environment: "PRODUCTION" });
    const old = await begin(), fresh = await begin(); const now = Date.now();
    const revoked = { state: "revoked", expiresAt: null, observedAt: now, reason: "provider_refund" };
    assert.equal((await bill("commit", { userId: A, environment: "PRODUCTION", generation: fresh.generation, state: revoked })).state, "revoked");
    const active = { state: "active", expiresAt: now+86400000, observedAt: now, reason: "provider_verified", transactionHash: "a".repeat(64) };
    assert.equal((await bill("commit", { userId: A, environment: "PRODUCTION", generation: old.generation, state: active })).state, "revoked");
    const next = await begin(); assert.equal((await bill("commit", { userId: A, environment: "PRODUCTION", generation: next.generation, state: active })).state, "active");
    const event = { id: "event-one", type: "CANCELLATION", environment: "PRODUCTION", timestamp: now, appUserIds: [a.appUserId], identityHold: false, fingerprint: "b".repeat(64) };
    assert.equal((await bill("enqueue", event)).status, "queued"); assert.equal((await bill("enqueue", event)).status, "queued");
    assert.equal((await bill("enqueue", { ...event, fingerprint: "c".repeat(64) })).error, "idempotency_conflict");
    const claimed = (await bill("claim_events", { environment: "PRODUCTION", limit: 5 })).events as Array<{ id: string; attempt: number }>;
    assert.equal(claimed.length,1); assert.equal(((await bill("claim_events", { environment: "PRODUCTION", limit: 5 })).events as unknown[]).length,0);
    await bill("finish_event", { ...claimed[0], environment: "PRODUCTION", status: "retry" });
    const retry = (await bill("claim_events", { environment: "PRODUCTION", limit: 5 })).events as Array<{ id: string; attempt: number }>;
    assert.equal(retry[0].attempt,2);
    // Stale lease holder cannot complete a newer attempt.
    await bill("finish_event", { ...claimed[0], environment: "PRODUCTION", status: "processed" });
    assert.equal((await db.query<{ status: string }>("select status from public.wd_billing_events")).rows[0].status,"leased");
    await bill("finish_event", { ...retry[0], environment: "PRODUCTION", status: "processed" });
    await bill("enqueue", { ...event, id: "sandbox-transfer", environment: "SANDBOX", type: "TRANSFER", identityHold: true });
    assert.equal((await begin()).binding && ((await begin()).binding as { held: boolean }).held, false);
    assert.equal(((await bill("begin", { userId: A, environment: "SANDBOX" })).binding as { held: boolean }).held,true);
    const other = await bill("begin", { userId: B, environment: "PRODUCTION" });
    assert.equal((await bill("commit", { userId: B, environment: "PRODUCTION", generation: other.generation, state: active })).state,"unknown");
    assert.equal(((await begin()).binding as { held: boolean }).held,true);
    await db.query("update public.wd_accounts set state='deleted' where user_id=$1",[A]);
    assert.equal((await begin()).error,"account_inactive");
    assert.equal((await bill("bind", { userId: A })).error,"account_inactive");
  } finally { await db.close(); }
});
